//! Auto-discovers every soundpack in `<workspace>/assets/soundpacks/` and
//! embeds its `config.json` + audio files directly into `thocci-core`.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

const AUDIO_EXTENSIONS: &[&str] = &["ogg", "wav", "mp3", "flac"];

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let packs_root = manifest_dir
        .join("..")
        .join("..")
        .join("assets")
        .join("soundpacks");
    let packs_root = fs::canonicalize(&packs_root)
        .unwrap_or_else(|err| panic!("Missing {}: {err}", packs_root.display()));

    println!("cargo:rerun-if-changed={}", packs_root.display());

    let mut dirs: Vec<(String, PathBuf)> = fs::read_dir(&packs_root)
        .expect("read assets/soundpacks")
        .filter_map(|entry| entry.ok())
        .filter_map(|entry| {
            let path = entry.path();
            if !path.is_dir() || !path.join("config.json").is_file() {
                return None;
            }
            let slug = entry.file_name().to_string_lossy().into_owned();
            Some((slug, path))
        })
        .collect();

    // Put cherry-mx first (default), banana-split second, then alphabetical.
    dirs.sort_by(|(a, _), (b, _)| pack_sort_key(a).cmp(&pack_sort_key(b)));

    let mut out = String::new();
    out.push_str("// @generated by crates/thocci-core/build.rs — do not edit manually.\n\n");
    out.push_str("pub(crate) struct EmbeddedFile {\n");
    out.push_str("    pub name: &'static str,\n");
    out.push_str("    pub bytes: &'static [u8],\n");
    out.push_str("}\n\n");
    out.push_str("pub(crate) struct EmbeddedPack {\n");
    out.push_str("    pub meta: BuiltinPackMeta,\n");
    out.push_str("    pub config: &'static [u8],\n");
    out.push_str("    pub files: &'static [EmbeddedFile],\n");
    out.push_str("}\n\n");

    let mut meta_entries = Vec::new();
    let mut pack_entries = Vec::new();

    for (slug, dir) in &dirs {
        println!("cargo:rerun-if-changed={}", dir.display());
        let config_path = dir.join("config.json");
        println!("cargo:rerun-if-changed={}", config_path.display());

        let display_name = read_display_name(&config_path, slug);
        let mut audio_files: Vec<(String, PathBuf)> = fs::read_dir(dir)
            .expect("read pack dir")
            .filter_map(|entry| entry.ok())
            .filter_map(|entry| {
                let path = entry.path();
                if !path.is_file() || !is_audio_file(&path) {
                    return None;
                }
                let name = entry.file_name().to_string_lossy().into_owned();
                Some((name, path))
            })
            .collect();
        audio_files.sort_by(|a, b| a.0.cmp(&b.0));

        let mut files_code = String::new();
        for (filename, path) in &audio_files {
            println!("cargo:rerun-if-changed={}", path.display());
            files_code.push_str(&format!(
                "            EmbeddedFile {{ name: {name:?}, bytes: include_bytes!({path:?}) }},\n",
                name = filename,
                path = path.to_string_lossy(),
            ));
        }

        let meta_literal = format!(
            "BuiltinPackMeta {{ id: {slug:?}, display_name: {display_name:?}, folder_name: {slug:?} }}"
        );
        meta_entries.push(format!("    {meta_literal},"));
        pack_entries.push(format!(
            "    EmbeddedPack {{\n        meta: {meta_literal},\n        config: include_bytes!({cfg:?}),\n        files: &[\n{files_code}        ],\n    }},",
            cfg = config_path.to_string_lossy(),
        ));
    }

    out.push_str("pub const BUILTIN_PACKS: &[BuiltinPackMeta] = &[\n");
    for entry in meta_entries {
        out.push_str(&entry);
        out.push('\n');
    }
    out.push_str("];\n\n");

    out.push_str("pub(crate) const EMBEDDED_PACKS: &[EmbeddedPack] = &[\n");
    for entry in pack_entries {
        out.push_str(&entry);
        out.push('\n');
    }
    out.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("embedded_packs.rs"), out).expect("write embedded_packs.rs");
}

fn pack_sort_key(slug: &str) -> (u8, &str) {
    match slug {
        "cherry-mx" => (0, slug),
        "banana-split" => (1, slug),
        _ => (2, slug),
    }
}

fn read_display_name(config_path: &Path, fallback: &str) -> String {
    let raw = fs::read_to_string(config_path).unwrap_or_default();
    let trimmed = raw.trim_start_matches('\u{feff}');
    serde_json::from_str::<serde_json::Value>(trimmed)
        .ok()
        .and_then(|val| val.get("name")?.as_str().map(str::to_owned))
        .filter(|name| !name.is_empty())
        .unwrap_or_else(|| fallback.to_owned())
}

fn is_audio_file(path: &Path) -> bool {
    path.extension()
        .and_then(|ext| ext.to_str())
        .map(|ext| AUDIO_EXTENSIONS.contains(&ext.to_ascii_lowercase().as_str()))
        .unwrap_or(false)
}
